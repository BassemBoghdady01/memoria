/**
 * MEMÓRIA · Build the catalogue seed migration from the imported assets.
 *
 * Reads supabase/seed/product-assets.json (written by
 * import-product-assets.mjs) and supabase/seed/catalog.json (the
 * owner-supplied product facts: names, prices, sizes, notes — anything
 * missing stays NULL and is reported, never invented), then writes
 * supabase/migrations/20261018090400_seed.sql.
 *
 * Usage: node scripts/build-seed.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';

const assets = JSON.parse(await readFile('supabase/seed/product-assets.json', 'utf8'));
const catalog = JSON.parse(await readFile('supabase/seed/catalog.json', 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const num = (v) => (v === null || v === undefined || v === '' ? 'null' : Number(v).toFixed(2));

const out = [];
const missing = [];
out.push(`-- MEMÓRIA · catalogue + reference data seed (generated by scripts/build-seed.mjs — do not edit by hand)

insert into public.categories (slug, name, sort_order) values
${catalog.categories.map((c, i) => `  (${q(c.slug)}, ${q(c.name)}, ${i})`).join(',\n')}
on conflict (slug) do nothing;
`);

assets.forEach((a, i) => {
  const facts = catalog.products.find((p) => p.slug === a.slug) || {};
  const name = facts.name || a.name;
  const need = [];
  if (!facts.category) need.push('gender category');
  if (!facts.variants?.length) need.push('sizes and EGP prices');
  if (!facts.description) need.push('description');
  if (!facts.top_notes?.length) need.push('fragrance notes');
  if (need.length) missing.push(`${name}: ${need.join(', ')}`);
  out.push(`-- ${name}
insert into public.products (slug, name, category_id, short_description, description, top_notes, heart_notes, base_notes,
  fragrance_family, concentration, story, status, featured, sort_order)
values (${q(a.slug)}, ${q(name)},
  ${facts.category ? `(select id from public.categories where slug = ${q(facts.category)})` : 'null'},
  ${q(facts.short_description)}, ${q(facts.description)},
  ${arr(facts.top_notes)}, ${arr(facts.heart_notes)}, ${arr(facts.base_notes)},
  ${q(facts.fragrance_family)}, ${q(facts.concentration)}, ${q(JSON.stringify(facts.story || {}))}::jsonb,
  'published', ${facts.featured ? 'true' : 'false'}, ${facts.sort_order ?? i})
on conflict (slug) do nothing;
`);
  (facts.variants || []).forEach((v, j) => {
    out.push(`insert into public.product_variants (product_id, sku, label, size_ml, price, sale_price, sort_order)
select id, ${q(v.sku || `${a.slug.toUpperCase()}-${v.size_ml || j}`)}, ${q(v.label || `${v.size_ml} ml`)}, ${v.size_ml ?? 'null'}, ${num(v.price)}, ${num(v.sale_price)}, ${j}
  from public.products where slug = ${q(a.slug)}
on conflict (sku) do nothing;
`);
  });
  const imgs = [
    ...a.images.map((im, j) => `(${q(im.src)}, ${q(im.srcset)}, ${q(`${name} by MEMÓRIA, ${im.label.toLowerCase()} view`)}, ${q(im.label)}, 'gallery', ${j})`),
    ...a.images.filter((im) => im.cutout).map((im, j) => `(${q(im.cutout)}, ${q(im.cutoutSrcset)}, ${q(`${name} by MEMÓRIA`)}, ${q(im.label)}, 'cutout', ${j})`),
  ];
  out.push(`insert into public.product_images (product_id, url, srcset, alt, view_label, kind, sort_order)
select p.id, v.url, v.srcset, v.alt, v.view_label, v.kind, v.sort_order
  from public.products p,
       (values
         ${imgs.join(',\n         ')}
       ) as v(url, srcset, alt, view_label, kind, sort_order)
 where p.slug = ${q(a.slug)}
   and not exists (select 1 from public.product_images x where x.product_id = p.id);
`);
});

out.push(`-- Egypt's governorates (fees and zones are configured by the owner in the dashboard)
insert into public.governorates (name_en, name_ar, sort_order) values
${catalog.governorates.map((g, i) => `  (${q(g[0])}, ${q(g[1])}, ${i})`).join(',\n')}
on conflict (name_en) do nothing;

-- Store settings. Public ones are readable by the storefront.
insert into public.store_settings (key, value, is_public) values
${Object.entries(catalog.settings)
  .map(([k, s]) => `  (${q(k)}, ${q(JSON.stringify(s.value))}::jsonb, ${s.public ? 'true' : 'false'})`)
  .join(',\n')}
on conflict (key) do nothing;
`);

await writeFile('supabase/migrations/20261018090400_seed.sql', out.join('\n'));
console.log('wrote supabase/migrations/20261018090400_seed.sql');
if (missing.length) {
  console.log('\nMissing product data (left empty, not invented):');
  missing.forEach((m) => console.log('  - ' + m));
}
